def track(old, new):
    for p in body.iter(qn("w:p")):
        for r in list(p.findall(W_R)):
            if not plain(r):
                continue
            t = r.find(W_T).text or ""
            k = t.find(old)
            if k < 0:
                continue
            rpr = r.find(W_RPR)
            # smallest change: keep the common prefix and suffix unchanged
            a = 0
            while a < min(len(old), len(new)) and old[a] == new[a]:
                a += 1
            b = 0
            while b < min(len(old), len(new)) - a and old[-1 - b] == new[-1 - b]:
                b += 1
            o_mid, n_mid = old[a:len(old) - b], new[a:len(new) - b]
            pre, post = t[: k + a], t[k + len(old) - b:]
            seq = []
            if pre:
                seq.append(mk_run(rpr, pre))
            if o_mid:
                de = OxmlElement("w:del")
                de.set(qn("w:id"), nid()); de.set(qn("w:author"), AUTHOR); de.set(qn("w:date"), DATE)
                de.append(mk_run(rpr, o_mid, deleted=True))
                seq.append(de)
            if n_mid:
                ins = OxmlElement("w:ins")
                ins.set(qn("w:id"), nid()); ins.set(qn("w:author"), AUTHOR); ins.set(qn("w:date"), DATE)
                ins.append(mk_run(rpr, n_mid))
                seq.append(ins)
            if post:
                seq.append(mk_run(rpr, post))
            for el in seq:
                r.addprevious(el)
            p.remove(r)
            return True
    return False


missed = [o for o, n in FIXES if not track(o, n)]
print("tracked changes:", len(FIXES) - len(missed), "missed:", missed)

# ---------- 2. reference bookmarks and citation links
paras = list(body.iter(qn("w:p")))
text = lambda p: "".join(t.text or "" for t in p.iter(W_T))
r0 = [i for i, p in enumerate(paras) if text(p).strip() == "References"][-1]
a0 = [i for i, p in enumerate(paras) if text(p).strip() == "Appendices"][-1]
refs = {}
for p in paras[r0 + 1:a0]:
    t = text(p)
    m = re.match(r"^(.+?),.*?\((\d{4}|n\.d\.)\)", t) or re.match(r"^(\S+) \((\d{4}|n\.d\.)\)", t)
    if not m:
        continue
    sur, yr = m.group(1).strip(), m.group(2)
    name = "ref_" + re.sub(r"\W", "", sur)[:24] + "_" + yr.replace(".", "")
    bs, be = OxmlElement("w:bookmarkStart"), OxmlElement("w:bookmarkEnd")
    bid = nid()
    bs.set(qn("w:id"), bid); bs.set(qn("w:name"), name); be.set(qn("w:id"), bid)
    ppr = p.find(qn("w:pPr"))
    (ppr.addnext(bs) if ppr is not None else p.insert(0, bs))
    p.append(be)
    refs[(sur, yr)] = name
print("reference entries bookmarked:", len(refs))

NAME = r"[A-Z][\w'’\-]+(?: [A-Z][\w'’\-]+)?"
pats = []
for (sur, yr), bm in refs.items():
    s = re.escape(sur)
    y = re.escape(yr)
    pat = rf"{s}(?: et al\.|(?:, {NAME})*,? and {NAME})?(?:, {y}| \({y}\))"
    pats.append((re.compile(pat), bm))

linked, cited = 0, set()
for i, p in enumerate(paras):
    if r0 <= i < a0:
        continue
    for r in list(p.findall(W_R)):
        if not plain(r):
            continue
        t = r.find(W_T).text or ""
        hits = []
        for rx, bm in pats:
            for m in rx.finditer(t):
                hits.append((m.start(), m.end(), bm))
        if not hits:
            continue
        hits.sort()
        keep, end = [], -1
        for h in hits:  # drop overlaps
            if h[0] >= end:
                keep.append(h)
                end = h[1]
        rpr = r.find(W_RPR)
        pos, seq = 0, []
        for s0, e0, bm in keep:
            if s0 > pos:
                seq.append(mk_run(rpr, t[pos:s0]))
            hl = OxmlElement("w:hyperlink")
            hl.set(qn("w:anchor"), bm)
            hl.set(qn("w:history"), "1")
            hl.append(mk_run(rpr, t[s0:e0]))
            seq.append(hl)
            pos = e0
            linked += 1
            cited.add(bm)
        if pos < len(t):
            seq.append(mk_run(rpr, t[pos:]))
        for el in seq:
            r.addprevious(el)
        p.remove(r)
print("in-text citations linked:", linked)
print("references never linked:", sorted(set(refs.values()) - cited))
d.save(OUT)
