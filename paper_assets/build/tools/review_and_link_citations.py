"""1. Suggested corrections as tracked changes (the author accepts or rejects each one in Word).
2. Bookmark on every reference-list entry and a link from every in-text citation to it."""
import copy, re, sys
from docx import Document
from docx.oxml import OxmlElement
from docx.oxml.ns import qn

SRC, OUT = sys.argv[1], sys.argv[2]
d = Document(SRC)
body = d.element.body
W_T, W_R, W_RPR = qn("w:t"), qn("w:r"), qn("w:rPr")
DATE, AUTHOR = "2026-11-21T09:00:00Z", "Claude"
_id = [9000]


def nid():
    _id[0] += 1
    return str(_id[0])


# Word's page-render markers split runs; they are regenerated by Word, so drop them and rejoin the text
for r in list(body.iter(W_R)):
    for m in r.findall(qn("w:lastRenderedPageBreak")):
        r.remove(m)
    ts = [k for k in r if k.tag != W_RPR]
    if len(ts) > 1 and all(k.tag == W_T for k in ts):
        ts[0].text = "".join(k.text or "" for k in ts)
        ts[0].set(qn("xml:space"), "preserve")
        for k in ts[1:]:
            r.remove(k)


def plain(r):  # a run with only formatting and one text element
    kids = [k for k in r if k.tag != W_RPR]
    return len(kids) == 1 and kids[0].tag == W_T


def mk_run(rpr, text, deleted=False):
    r = OxmlElement("w:r")
    if rpr is not None:
        r.append(copy.deepcopy(rpr))
    t = OxmlElement("w:delText" if deleted else "w:t")
    t.text = text
    t.set(qn("xml:space"), "preserve")
    r.append(t)
    return r


